#!/usr/bin/env python3
"""Extract the AVX2 Q4_K GEMV kernel body from the ggml source tree.

The extraction is used by tests/bench-cpu-kern.cpp to build experimental variants
of the kernel (e.g. with software prefetching) from the *real* source text, so the
benchmark always measures code that is identical to the shipped kernel apart from
the explicitly injected change.

usage: python bench/gen_q4k_body.py > llama.cpp-b10991/tests/q4k_gemv_body.inc
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "llama.cpp-b10991", "ggml", "src", "ggml-cpu", "arch", "x86", "repack.cpp")

FUNC = "void ggml_gemv_q4_K_8x8_q8_K("


def extract(text: str) -> str:
    start = text.index(FUNC)
    end = text.index("\n}\n", start) + 3
    return text[start:end]


def main() -> int:
    with open(SRC, "r", encoding="utf-8") as f:
        text = f.read()

    # the FP16 -> FP32 load helpers used by the kernel are #defined at the top of
    # repack.cpp, outside of the function: carry them over so the generated body
    # compiles to the very same code
    pre_start = text.index('#if defined(__AVX__)')
    pre_end = text.index('static inline int nearest_int(float fval)')
    prelude = text[pre_start:pre_end]

    fn = extract(text)

    # The generator must always yield the *pre-optimisation* baseline: strip the
    # software prefetch that Build 31 added to the shipped kernel (the benchmark
    # variants inject their own prefetch at a configurable distance).
    marker = '// Prefetch the weights that will be consumed two iterations later.'
    if marker in fn:
        i = fn.index(marker)
        # back up to the start of the comment line
        i = fn.rfind(chr(10), 0, i) + 1
        close = chr(10) + '                }' + chr(10)
        j = fn.index(close, i) + len(close)
        while fn[j] == chr(10):
            j += 1
        fn = fn[:i] + fn[j:]
        sys.stderr.write('gen_q4k_body: stripped the Build 31 prefetch block from the baseline copy' + chr(10))

    body = prelude + fn
    # rename + inject the prefetch experiment hook
    body = body.replace(FUNC, "void GEMV_FN(", 1)
    anchor = "            for (int64_t b = 0; b < nb; b++) {\n"
    if anchor not in body:
        print("anchor not found", file=sys.stderr)
        return 1
    inject = """                if (GEMV_PDIST > 0 && (GEMV_GUARD == 0 || b + GEMV_PDIST < nb)) {
                    // experimental: prefetch the block that will be consumed GEMV_PDIST iterations later
                    const char * pf = (const char *) (b_ptr + b + GEMV_PDIST);
                    for (int off = 0; off < (int) sizeof(block_q4_Kx8); off += 64) {
                        _mm_prefetch(pf + off, _MM_HINT_T0);
                    }
                }
                if (GEMV_PDIST < 0) {
                    // experimental: cheap variant, only pull the head of the block that is
                    // -GEMV_PDIST iterations ahead (lets the hardware prefetcher do the rest)
                    const char * pf = (const char *) (b_ptr + b - GEMV_PDIST);
                    _mm_prefetch(pf, _MM_HINT_T0);
                }
"""
    body = body.replace(anchor, anchor + inject, 1)

    sys.stdout.write("// generated by bench/gen_q4k_body.py - do not edit\n")
    sys.stdout.write(body)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
